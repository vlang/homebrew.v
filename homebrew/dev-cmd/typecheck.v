// 242:           case current
// 243:           when Prism::ConstantPathNode
// 244:             parts.unshift(current.name.to_s)
// 245:             current = current.parent
// 246:           when Prism::ConstantReadNode
// 247:             parts.unshift(current.name.to_s)
