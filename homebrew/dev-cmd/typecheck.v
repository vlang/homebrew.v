// 218:       def extract_full_name(node)
// 219:         case node
// 220:         when Prism::ModuleNode, Prism::ClassNode
// 221:           parts = []
// 222:
// 223:           constant_path = node.constant_path
// 224:           if constant_path.is_a?(Prism::ConstantReadNode)
